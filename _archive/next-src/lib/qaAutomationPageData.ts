export function qaAutoFaqPlainText(faq: QaAutoFaqItem): string {
  const parts = [faq.answer];
  if (faq.bullets?.length) {
    parts.push(faq.bullets.map((item) => `- ${item}`).join("\n"));
  }
  if (faq.closing) parts.push(faq.closing);
  return parts.join("\n");
}

